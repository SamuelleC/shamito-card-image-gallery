// Regenerates data/cards.js from data/cube-list.txt using the Scryfall API.
// Usage: node scripts/build-cards.mjs
import { readFile, writeFile } from "node:fs/promises";

const LIST = new URL("../data/cube-list.txt", import.meta.url);
const OUT = new URL("../data/cards.js", import.meta.url);
const HEADERS = { "User-Agent": "ShamitoPauperCube/1.0", Accept: "application/json", "Content-Type": "application/json" };

const rows = (await readFile(LIST, "utf8"))
  .split(/\r?\n/)
  .map((l) => l.replace(/^\uFEFF/, "").trim())
  .filter((l) => l && !l.startsWith("#"))
  .map((l) => {
    const [section, name, set, collector] = l.split("|");
    return { section, name, set, collector };
  });

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const found = new Map();

for (let i = 0; i < rows.length; i += 75) {
  const batch = rows.slice(i, i + 75);
  const res = await fetch("https://api.scryfall.com/cards/collection", {
    method: "POST",
    headers: HEADERS,
    body: JSON.stringify({ identifiers: batch.map((r) => ({ set: r.set, collector_number: r.collector })) }),
  });
  if (!res.ok) throw new Error(`Scryfall error ${res.status}: ${await res.text()}`);
  const json = await res.json();
  for (const nf of json.not_found ?? []) console.warn("Not found:", nf);
  for (const c of json.data) found.set(`${c.set}|${c.collector_number}`.toLowerCase(), c);
  await sleep(150);
}

const imagesOf = (c) =>
  c.image_uris
    ? [{ normal: c.image_uris.normal, large: c.image_uris.large }]
    : (c.card_faces ?? []).filter((f) => f.image_uris).map((f) => ({ normal: f.image_uris.normal, large: f.image_uris.large }));

const front = (c) => (c.card_faces && !c.mana_cost && c.card_faces[0].mana_cost !== undefined ? c.card_faces[0] : c);

const cards = rows.map((r) => {
  const c = found.get(`${r.set}|${r.collector}`.toLowerCase());
  if (!c) throw new Error(`Missing card: ${r.name} (${r.set} ${r.collector})`);
  const f = front(c);
  return {
    name: r.name,
    section: r.section,
    manaCost: f.mana_cost ?? "",
    cmc: c.cmc ?? 0,
    colors: c.color_identity ?? [],
    type: f.type_line ?? c.type_line,
    rarity: c.rarity,
    set: c.set.toUpperCase(),
    setName: c.set_name,
    collector: c.collector_number,
    artist: c.artist ?? "",
    images: imagesOf(c),
    scryfall: c.scryfall_uri,
  };
});

await writeFile(OUT, `// Generated by scripts/build-cards.mjs — do not edit by hand.\nwindow.CUBE_CARDS = ${JSON.stringify(cards, null, 1)};\n`);
console.log(`Wrote ${cards.length} cards to data/cards.js`);
